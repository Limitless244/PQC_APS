package com.pqcaps.common;

import java.io.Serial;
import java.io.Serializable;

/**
 * An AES-GCM encrypted application-layer record.
 *
 * <p>Layout (conceptual): {@code [sequenceNumber (8 B) | nonce (12 B) | ciphertext+tag]}
 *
 * <p>The {@code sequenceNumber} is included in the GCM Additional Authenticated Data
 * (AAD) so the receiver can detect out-of-order or replayed records (when the
 * sequence check is enabled).
 *
 * <p><b>VULN-2 note</b>: in Phase 1 the receiver does NOT enforce that
 * {@code sequenceNumber} is strictly monotonically increasing. An attacker can
 * replay any old record and it will be accepted. See {@code HandshakeConfig.skipSequenceCheck}.
 *
 * <p><b>VULN-3 note</b>: the {@code nonce} is generated by a simple counter that
 * resets to 0 on each channel creation. If the same session key is reused across
 * restarts, nonces repeat, destroying GCM security.
 *
 * @param sequenceNumber monotonically increasing counter, included in GCM AAD
 * @param nonce          12-byte GCM nonce derived from the sequence counter
 * @param ciphertext     AES-256-GCM ciphertext with 16-byte tag appended
 */
public record EncryptedRecord(
        long   sequenceNumber,
        byte[] nonce,
        byte[] ciphertext
) implements Serializable {

    @Serial
    private static final long serialVersionUID = 1L;
}
